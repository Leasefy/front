/**
 * Label legible para el "tipo de contrato" del lado del usuario. Como el backend no modela
 * `type` en el contract, derivamos el label del `contractOrigin`.
 */
export function getContractTypeLabel(
  contract: Pick<Contract, 'contractOrigin'>,
  locale: 'es' | 'en' = 'es',
): string {
  if (contract.contractOrigin === 'UPLOADED_PDF') {
    return locale === 'es'
      ? 'Contrato subido por el propietario'
      : 'Contract uploaded by landlord';
  }
  if (contract.contractOrigin === 'GENERATED') {
    return locale === 'es'
      ? 'Contrato generado por la plataforma'
      : 'Contract generated by the platform';
  }
  return locale === 'es' ? 'Contrato de arrendamiento' : 'Rental contract';
}

