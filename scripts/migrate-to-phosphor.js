// Find all TSX files
const srcDir = path.join(__dirname, '../src');

function getAllTsxFiles(dir) {
  const results = [];
  const items = fs.readdirSync(dir);

  for (const item of items) {
    const fullPath = path.join(dir, item);
    const stat = fs.statSync(fullPath);

    if (stat.isDirectory()) {
      results.push(...getAllTsxFiles(fullPath));
    } else if (item.endsWith('.tsx')) {
      results.push(fullPath);
    }
  }

  return results;
}

function migrateFile(filePath) {
  let content = fs.readFileSync(filePath, 'utf8');
  let modified = false;

  // Find lucide-react imports
  const importRegex = /import\s*\{([^}]+)\}\s*from\s*['"]lucide-react['"]/g;
  const matches = content.matchAll(importRegex);

  for (const match of matches) {
    const importStatement = match[0];
    const iconsStr = match[1];

    // Parse icon names
    const icons = iconsStr.split(',').map(s => s.trim()).filter(s => s);

    // Map to Phosphor icons
    const phosphorIcons = [];
    const unmapped = [];

    for (const icon of icons) {
      // Handle aliased imports like "X as CloseIcon"
      const parts = icon.split(/\s+as\s+/);
      const originalIcon = parts[0].trim();
      const alias = parts[1]?.trim();

      const phosphorIcon = iconMapping[originalIcon];
      if (phosphorIcon) {
        if (alias) {
          phosphorIcons.push(`${phosphorIcon} as ${alias}`);
        } else {
          phosphorIcons.push(phosphorIcon);
        }
      } else {
        unmapped.push(originalIcon);
        // Keep original if no mapping (will need manual fix)
        if (alias) {
          phosphorIcons.push(`${originalIcon} as ${alias}`);
        } else {
          phosphorIcons.push(originalIcon);
        }
      }
    }

    if (unmapped.length > 0) {
      console.log(`  ⚠️  Unmapped icons in ${path.basename(filePath)}: ${unmapped.join(', ')}`);
    }

    // Create new import
    const newImport = `import { ${phosphorIcons.join(', ')} } from '@phosphor-icons/react'`;

    content = content.replace(importStatement, newImport);
    modified = true;
  }

  if (modified) {
    fs.writeFileSync(filePath, content);
    return true;
  }

  return false;
}

