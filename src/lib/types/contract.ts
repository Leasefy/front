/**
 * Full contract instance with signatures and terms
 */
export interface Contract {
  id: string;
  applicationId?: string;
  /**
   * `null` cuando el contrato es un MIGRADO al que la inmobiliaria decidió
   * no importarle el inmueble (T-0033). Es la fuente de verdad de "¿tiene
   * inmueble?" — clave todo render de "Sin inmueble" en esto, nunca en
   * `propertyAddress` vacío.
   */
  propertyId: string | null;
  /**
   * `null` en un contrato MIGRADO (T-0031) sin correo de inquilino — existe
   * como `Contract` igual, sin usuario inquilino asociado. No es un dato
   * ausente por error: es el estado real de una cartera migrada a medias.
   */
  tenantId: string | null;
  landlordId: string;
  /**
   * Número consecutivo del contrato (T-0040). Asignado por el servidor,
   * arranca en 1 por inmobiliaria — o por propietario cuando el contrato no
   * tiene inmobiliaria. Independiente del código de inmueble.
   *
   * Misma forma que `BackendProperty.code` y que el dominio `Property.code`:
   * un solo shape para un solo concepto en todo el front. Ausente sólo cuando
   * el `back` es anterior a T-0040; en ese caso **no se renderiza nada**
   * (nunca `—`, nunca `#0`). Guarda con `!= null`.
   */
  code?: number;
  /**
   * El número con el que la inmobiliaria conoce el contrato (su sistema
   * anterior), guardado al migrar. Es el que se lee grande en un contrato
   * migrado; `code` va al lado, nombrado como el de Leasefy. Ver
   * `lib/contratos/numero-del-contrato.ts`. `null` = no hay número;
   * `undefined` = el back no lo mandó.
   */
  externalId?: string | null;
  status: ContractStatus;

  // ── Terminación anticipada (back: migración 20260915170000) ──────────────
  //
  // 🔴 `status` NO distingue «lo terminaron antes de tiempo» de «se venció
  // solo»: los dos son `expired`, porque en el back `EXPIRED` ya significa
  // «terminado» y así están guardados los 1.145 contratos migrados como
  // «Terminado». Quien los distingue es `terminadoEn`.
  //
  // `undefined` = la migración todavía no está aplicada en esa base y el
  // back omite las columnas. Se lee igual que «no se terminó».
  /** `'2026-09-30'` — el día en que se terminó antes de tiempo. */
  terminadoEn?: string | null;
  /** El código del motivo (`MUTUO_ACUERDO`, `VENTA_DEL_INMUEBLE`, …). */
  motivoDeTerminacion?: string | null;
  notaDeTerminacion?: string | null;
  /** Hasta cuándo se había pactado, antes de que la terminación moviera `endDate`. */
  finPactadoOriginal?: string | null;

  // Snapshot fields (Opción A — capturados al crear el contrato, inmutables).
  // Pueden venir '' cuando el backfill no encontró el dato original.
  propertyAddress: string;
  propertyCity: string;
  tenantName: string;
  tenantEmail: string;
  tenantPhone: string;
  tenantDocument: string;
  landlordName: string;
  landlordEmail: string;
  landlordDocument: string;

  /**
   * `null` en un contrato MIGRADO sin ese dato (T-0031, D6 — nunca `0`/una
   * fecha inventada como sentinela de "desconocido"). Un renderizador que
   * recibe `null` acá DEBE mostrarlo como ausente — nunca formatear un
   * valor por default (`formatCurrency`/`formatDate` de `@/lib/format`
   * NO son null-safe en el sentido correcto para estos campos: resuelven a
   * "$ 0"/epoch, indistinguible de un dato real).
   */
  monthlyRent: number | null;
  adminFee: number;
  startDate: string | null;      // ISO date
  endDate: string | null;        // ISO date
  paymentDueDay: number | null;  // 1-28
  /**
   * Términos de cobro. `diasDePlazo: null` = hereda los de la inmobiliaria.
   * Opcionales en el tipo para no obligar a cada fixture viejo a declararlos;
   * el mapper (`mapBackendContract`) los llena SIEMPRE.
   */
  /**
   * 🔴 LA REFERENCIA DE RECAUDO: el número con el que este inquilino paga y
   * que el banco escribe en la línea del extracto. Es lo que deja que la
   * conciliación reconozca el pago en vez de adivinar por apellido.
   *
   * `null`/ausente = la inmobiliaria no cargó ninguna (o el back es anterior a
   * esta rama): se usa el consecutivo del contrato (`code`).
   */
  referenciaDeRecaudo?: string | null;
  prorratearPrimerMes?: boolean;
  diasDePlazo?: number | null;

  // ─── Administración ───────────────────────────────────────────────────────
  // No viajan en el documento firmado: corregirlos no invalida ninguna firma.
  // Se editan por PATCH /contracts/:id/administracion.
  //
  // Ver PerfilTributario / PerfilesDelContrato más abajo en este archivo.

  /** Decide el IVA del canon: vivienda excluida, comercial gravada. */
  usoInmueble?: 'VIVIENDA' | 'COMERCIAL' | null;
  periodicidad?: 'MENSUAL' | 'BIMESTRAL' | 'TRIMESTRAL' | 'SEMESTRAL' | 'ANUAL' | null;
  /** La del contrato — la que trajo el archivo migrado. */
  comisionPorcentaje?: number | null;
  /**
   * La de la consignación: **es la que liquida**. La dispersión y el extracto
   * leen ésta para pagarle al propietario. Viaja aparte para poder mostrar el
   * desacuerdo cuando las dos no coinciden, en vez de elegir un número.
   */
  comisionDeConsignacion?: number | null;
  /**
   * El propietario de verdad: la ficha de la consignación del inmueble.
   * `landlordName` en un contrato de inmobiliaria es el usuario que lo creó
   * o migró — no el dueño. `null` = sin inmueble o sin consignación;
   * `undefined` = el back no lo mandó (lista, respuesta vieja).
   */
  propietarioDeLaConsignacion?: {
    id: string;
    name: string;
    documentNumber: string;
  } | null;

  /**
   * TODOS los dueños del inmueble, con su porcentaje y su parte del canon.
   * Con un solo dueño es una lista de uno al 100 %; `undefined` = el back no
   * lo mandó (lista, respuesta vieja) y la ficha cae a
   * `propietarioDeLaConsignacion`.
   */
  propietariosDelContrato?: PropietariosDelContrato | null;
  /** Todos los inquilinos, el principal primero y marcado. */
  inquilinosDelContrato?: InquilinoDelContrato[] | null;

  /**
   * Quién retiene qué. La retención la practica **quien paga**, así que sin
   * esto la liquidación de cada concepto era una suposición.
   *
   * Cada perfil trae `esPorDefecto`: si la parte no tiene el dato configurado
   * se deduce del tipo de persona y se marca. Un supuesto y un hecho son cinco
   * booleanos idénticos — si no se distinguen, la pantalla muestra una
   * retención inventada con la misma cara que una real.
   */
  perfilesTributarios?: PerfilesDelContrato | null;
  /** El régimen ya resuelto por el back, con el origen de cada valor. */
  regimenTributario?: RegimenTributarioDelContrato | null;
  /**
   * Cómo se llama el escenario que forman las dos partes, y qué genera.
   * Opcional porque no todos los cables del contrato lo traen (la lista, por
   * ejemplo, sólo lo traería a costa de una consulta por fila).
   */
  escenarioTributario?: EscenarioTributarioDelContrato | null;
  /** null = heredar de la ficha del propietario. */
  arrendadorResponsableIva?: boolean | null;

  /**
   * Lo guardado tal cual, para poblar el formulario. `perfilesTributarios` ya
   * trae los defaults mezclados y no distingue «configurado como NATURAL» de
   * «vacío, y NATURAL es el default» — abrir el editor con eso convertiría un
   * vacío en una respuesta al guardar.
   */
  inquilinoTipoPersona?: 'NATURAL' | 'JURIDICA' | null;
  inquilinoResponsableIva?: boolean | null;
  inquilinoRetenedorRenta?: boolean | null;
  inquilinoRetenedorIva?: boolean | null;
  inquilinoRetenedorIca?: boolean | null;

  // Signatures
  landlordSignature: Signature | null;
  tenantSignature: Signature | null;

  // Uploaded PDF flow. `MIGRATED` = entró por la migración (casi siempre sin PDF).
  contractOrigin?: 'GENERATED' | 'UPLOADED_PDF' | 'MIGRATED';
  uploadedPdfPath?: string;
  insuranceTier?: 'NONE' | 'BASIC' | 'PREMIUM';
  customClauses?: Array<{ title: string; content: string }>;

  // Metadata
  createdAt: string;
  updatedAt: string;
  /** Fecha cuando el contrato quedó SIGNED (ambas partes firmaron). */
  signedAt?: string | null;
  /** Fecha cuando el contrato pasó a ACTIVE. */
  activatedAt?: string | null;

  // ─── Legacy / deprecated — mantenidos como opcionales hasta migrar consumers ─
  /** @deprecated backend no modela templates. Usar `contractOrigin` para inferir el tipo. */
  templateId?: string;
  /** @deprecated backend no modela type. Usar `contractOrigin` para el label. */
  type?: ContractType;
  /** @deprecated backend no modela garantías. */
  guaranteeType?: 'poliza' | 'codeudor';
  /** @deprecated backend no modela garantías. */
  guaranteeDetails?: string;
  /** @deprecated backend no modela cláusulas no negociables. */
  nonNegotiableClauses?: ContractClause[];
  /** @deprecated backend no modela condiciones especiales. */
  specialConditions?: string;

  // Hash SHA-256 del PDF final — disponible cuando el contrato está SIGNED.
  documentHash?: string;

  /**
   * @deprecated el backend no devuelve el timeline como array. Ver `AuditTrail` component,
   * que ahora deriva el timeline de los campos del contrato (createdAt + signatures + signedAt + activatedAt).
   */
  auditTrail?: ContractAuditEvent[];
}

